"""Оборудование, которое бригада везёт клиенту.

Заказчик назвал оборудование дополнительным параметром заявки: клиент при
подключении выбрал опцией установку роутера, приставки или колонки. В
выгрузке этого поля нет, но тип работ часто называет устройство прямо, и
тогда придумывать нечего.

Оборудование следует из плана, а не ограничивает его: по маршруту бригады
считается ведомость на выдачу в офисе, и на этом всё.
"""
from __future__ import annotations

import hashlib

ROUTER = "Роутер"
TV_BOX = "ТВ-приставка"
SPEAKER = "Умная колонка"

EQUIPMENT = (ROUTER, TV_BOX, SPEAKER)

#: Типы работ, которые прямо называют устройство. Здесь мы ничего не
#: придумываем: что написано в наряде, то бригада и везёт.
BY_TYPE_HD: dict[str, tuple[str, ...]] = {
    "Роутер. Замена техническим специалистом": (ROUTER,),
    "ТВ. Замена приставки техником": (TV_BOX,),
    "TVE/ENT. Замена приставки техником": (TV_BOX,),
    "Дозаказ оборудования": (ROUTER,),
    "Заказ подключения/Дозаказ оборудования": (ROUTER,),
}

#: Доли для подключений, где тип работ устройство не называет. Допущение:
#: клиент мог заказать опцию, а в выгрузке этого нет. Показывается в карточке
#: «как считаем» и меняется одной строкой.
SYNTHETIC_SHARES: tuple[tuple[str, float], ...] = (
    (ROUTER, 0.55),
    (TV_BOX, 0.20),
    (SPEAKER, 0.10),
)

#: Типы заявок, для которых достраиваем набор. Ремонт и авария едут без
#: оборудования: там чинят линию, а не ставят устройство.
SYNTHETIC_TYPES_BK = frozenset({"Подключение"})


def _dice(order_id: str, salt: str) -> float:
    """Число в [0, 1), устойчивое между запусками.

    Случайность здесь недопустима: план должен воспроизводиться, иначе одна и
    та же заявка в двух прогонах повезёт разное.
    """
    digest = hashlib.sha256(f"{order_id}:{salt}".encode()).digest()
    return int.from_bytes(digest[:4], "big") / 2 ** 32


def equipment_for(type_bk: str, type_hd: str, order_id: str) -> list[str]:
    """Что бригада везёт по этой заявке."""
    named = BY_TYPE_HD.get(type_hd.strip())
    if named is not None:
        return list(named)
    if type_bk.strip() not in SYNTHETIC_TYPES_BK:
        return []
    return [name for name, share in SYNTHETIC_SHARES
            if _dice(order_id, name) < share]
