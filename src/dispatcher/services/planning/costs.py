"""Веса целевой функции и предел времени расчёта."""
from __future__ import annotations

DROP_PENALTY_NORMAL = 5_000_000      # не назначить обычную заявку
DROP_PENALTY_URGENT = 20_000_000     # не назначить аварию - вчетверо дороже
DROP_PENALTY_HIGH = 8_000_000        # не назначить подключение

#: Порядок задан постановщиком: авария, подключение, ремонт и дозаказ по
#: остаточному принципу. Вес подключения выбран в вилке: больше одного
#: ремонта, но меньше двух. Подключение занимает 90 минут против 50, то есть
#: на его месте помещаются почти два ремонта, и при весе 12 000 000 решатель
#: менял два ремонта на одно подключение - Югоцентр закрывал 48 заявок
#: вместо 50. Главная метрика ТЗ это число закрытых заявок, поэтому
#: приоритет разводит только равный выбор, а объём не размывает.
ENGINEER_FIXED_COST = 120_000        # вывод ещё одного исполнителя ≈ 120 км пробега

#: Цена каждой минуты, на которую срочная заявка отложена после открытия
#: её окна. Постановщик просил у аварий окно в сутки и выполнение «как
#: можно раньше»; без этой цены суточное окно означало «когда угодно», и
#: авария, известная с утра, вставала в маршрут на 20:22. Минута стоит
#: трети километра: четыре часа отсрочки весят как 80 км, но заявку
#: (5 000 000) не перевешивают никогда.
URGENT_DELAY_COST_PER_MIN = 300

#: Верхняя граница расчёта: предохранитель от зависания, а не ограничитель
#: качества. Замер показал, что при 30 секундах поиск обрывался временем и
#: отдавал то, что успел: 153 км на пределе 10 с, 142.0 на 30 с и 141.8,
#: когда времени хватало. Результат зависел от загрузки машины, то есть
#: воспроизводимость держалась на удаче. Самый долгий участок набирает
#: счётный предел за полторы минуты, отсюда запас втрое.
DEFAULT_TIME_LIMIT_SEC = 300
