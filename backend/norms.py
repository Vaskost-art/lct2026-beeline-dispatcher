"""Нормативы и правила восстановления полей, которых нет в исходных данных.

Исходные выгрузки — реальные обезличенные наряды FSM. В них есть тип работ,
адрес, район и временное окно, но НЕТ длительности, навыков, транспорта и смен.
Всё, что мы достраиваем, собрано здесь в одном месте: каждое допущение можно
показать эксперту и поменять одной строкой.

Источник правил — справочники ТЗ (п. 2.4.1) и структура самих данных.
"""
from __future__ import annotations

from domain import (
    SKILL_LOCAL, SKILL_CONNECT, SKILL_EMERGENCY,
    VEHICLE_CAR, VEHICLE_BIKE, VEHICLE_FOOT, VEHICLE_TRANSIT,
    PRIORITY_NORMAL, PRIORITY_URGENT,
)

# --- 1. Навык -----------------------------------------------------------------
# Колонка «Тип заявки BK» ложится на справочник навыков ТЗ один в один.
SKILL_BY_TYPE_BK = {
    "Локальная заявка": SKILL_LOCAL,
    "Подключение": SKILL_CONNECT,
    "Дозаказ": SKILL_CONNECT,
    "Глобальная проблема": SKILL_EMERGENCY,
}
DEFAULT_SKILL = SKILL_LOCAL

# --- 2. Длительность работ, минуты -------------------------------------------
# Нормативы по «Тип заявки HD». Значения — отраслевые ориентиры для монтажных
# работ ШПД: подключение с прокладкой кабеля дольше, диагностика и замена
# абонентского оборудования короче.
DURATION_BY_TYPE_HD = {
    # подключения и дозаказы
    "Конвергенция абонента": 90,
    "Заявка на подключение": 120,
    "Заказ подключения/Дозаказ оборудования": 90,
    "Дозаказ оборудования": 60,
    # аварии
    "Авария": 120,
    "Информация": 30,
    # локальные работы
    "Нет линка": 60,
    "Работа с кабелем": 90,
    "Переключение на Гбит/с": 60,
    "Разрывы": 45,
    "Низкая скорость": 45,
    "Рост ошибок на порту": 45,
    "IP-адрес 169...": 30,
    "Мониторинг": 30,
    "Роутер. Замена техническим специалистом": 40,
    "TVE/ENT. Замена приставки техником": 40,
    "ТВ. Замена приставки техником": 40,
    "TVE/ENT. Другие ошибки": 40,
}
DEFAULT_DURATION = 60

# Гигабитное подключение требует протяжки нового кабеля — надбавка к норме.
GIGABIT_EXTRA_MIN = 30

# --- 3. Приоритет -------------------------------------------------------------
# «Срочная» = авария (влияет на многих абонентов) либо уже просроченный наряд.
URGENT_TYPES_BK = {"Глобальная проблема"}
URGENT_STATUSES_BK = {"Просрочена"}

# --- 4. Требуемый тип транспорта (ограничение «Ресурс» из ТЗ) ------------------
# Ограничение ставится только там, где работа физически требует машины:
# тяжёлое оборудование, бухта кабеля, инструмент аварийной бригады.
# В остальных заявках ограничения нет (ТЗ: «указывается только при наличии»).
CAR_REQUIRED_TYPES_HD = {"Авария", "Работа с кабелем"}
CAR_REQUIRED_IF_GIGABIT = True

# --- 5. Скорости движения, км/ч ----------------------------------------------
# Средние скорости «от двери до двери» в Москве с учётом трафика и парковки.
SPEED_KMH = {
    VEHICLE_CAR: 22.0,
    VEHICLE_TRANSIT: 15.0,
    VEHICLE_BIKE: 12.0,
    VEHICLE_FOOT: 4.5,
}

# Коэффициент извилистости: по прямой (haversine) -> по улично-дорожной сети.
# 1.35 — общепринятая оценка для плотной городской застройки.
DETOUR_FACTOR = 1.35

# --- 6. Правила восстановления транспорта исполнителя -------------------------
# Тип транспорта выводится из географии реальных маршрутов бригады в
# контрольном распределении: чем шире разлёт точек, тем «быстрее» транспорт.
SPREAD_CAR_KM = 6.0        # разлёт больше — только автомобиль
SPREAD_TRANSIT_KM = 3.0    # средний разлёт в центре — общественный транспорт
SPREAD_BIKE_KM = 1.5       # компактный участок — велосипед
                           # меньше — пешком

# Районы исторического центра: там быстрее на метро, чем на машине.
CENTRAL_DISTRICTS = {
    "Хамовники", "Замоскворечье", "Басманный", "Таганский", "Даниловский",
    "Донской", "Гагаринский",
}

# --- 6.1. Перерыв на обед -----------------------------------------------------
# Смена считалась сплошной, и это завышало ёмкость дня почти на час на бригаду.
# Перерыв ставится в середину смены: у разных бригад смены разные, поэтому
# обедают они не одновременно и провала по всему району не возникает.
BREAK_MIN = 45                  # длительность перерыва
BREAK_MIN_SHIFT_MIN = 6 * 60    # смена короче — работают без перерыва
BREAK_PREFERRED = 13 * 60       # целимся в час дня
BREAK_LEAD_MIN = 2 * 60         # не раньше двух часов после начала смены
BREAK_TAIL_MIN = 60             # и не в последний час смены
BREAK_SPREAD_MIN = 30           # разброс между бригадами, чтобы не обедали разом

# --- 6.1. Перерыв на обед -----------------------------------------------------
# Смена считалась сплошной, и это завышало ёмкость дня почти на час на бригаду.
# Время обеда не фиксируется: эти минуты вычитаются из ёмкости дня. Жёсткий
# интервал в модели пробовался и был отвергнут — он ухудшал пробег на 13–38%,
# не давая взамен ничего, кроме точного времени обеда.
BREAK_MIN = 45                  # длительность перерыва
BREAK_MIN_SHIFT_MIN = 6 * 60    # смена короче — работают без перерыва

# --- 7. Смена -----------------------------------------------------------------
SHIFT_LEAD_MIN = 60        # запас до первого окна на дорогу от базы
SHIFT_TAIL_MIN = 30        # запас после последнего окна
SHIFT_MIN_LENGTH_MIN = 8 * 60
SHIFT_EARLIEST = 8 * 60    # 08:00
SHIFT_LATEST = 23 * 60     # 23:00


def skill_for(type_bk: str) -> str:
    return SKILL_BY_TYPE_BK.get(type_bk.strip(), DEFAULT_SKILL)


def duration_for(type_hd: str, gigabit: bool) -> int:
    base = DURATION_BY_TYPE_HD.get(type_hd.strip(), DEFAULT_DURATION)
    return base + (GIGABIT_EXTRA_MIN if gigabit else 0)


def priority_for(type_bk: str, status_bk: str) -> str:
    if type_bk.strip() in URGENT_TYPES_BK:
        return PRIORITY_URGENT
    if status_bk.strip() in URGENT_STATUSES_BK:
        return PRIORITY_URGENT
    return PRIORITY_NORMAL


def required_vehicle_for(type_hd: str, gigabit: bool) -> str | None:
    if type_hd.strip() in CAR_REQUIRED_TYPES_HD:
        return VEHICLE_CAR
    if gigabit and CAR_REQUIRED_IF_GIGABIT:
        return VEHICLE_CAR
    return None


def vehicle_for_spread(spread_km: float, needs_car: bool, central: bool) -> str:
    """Тип транспорта бригады по разлёту её точек в контрольном распределении."""
    if needs_car or spread_km >= SPREAD_CAR_KM:
        return VEHICLE_CAR
    if central and spread_km >= SPREAD_BIKE_KM:
        return VEHICLE_TRANSIT
    if spread_km >= SPREAD_TRANSIT_KM:
        return VEHICLE_CAR
    if spread_km >= SPREAD_BIKE_KM:
        return VEHICLE_BIKE
    return VEHICLE_FOOT


def break_window(shift_start: int, shift_end: int,
                 spread: int = 0) -> tuple[int, int] | None:
    """Окно перерыва: целимся в час дня, но не в самое начало и не в конец смены.

    `spread` разводит бригады по времени: если все уйдут на обед разом,
    в середине дня получится провал по всему району.
    Возвращает None, если смена слишком коротка для перерыва.
    """
    if shift_end - shift_start < BREAK_MIN_SHIFT_MIN:
        return None

    earliest = shift_start + BREAK_LEAD_MIN
    latest = shift_end - BREAK_TAIL_MIN - BREAK_MIN
    if latest < earliest:
        return None

    start = min(max(BREAK_PREFERRED + spread, earliest), latest)
    return start, start + BREAK_MIN


def break_minutes(shift_start: int, shift_end: int) -> int:
    """Сколько минут смены уходит на перерыв. Короткая смена — без перерыва."""
    if shift_end - shift_start < BREAK_MIN_SHIFT_MIN:
        return 0
    return BREAK_MIN


def shift_bounds(first_window_start: int, last_window_end: int) -> tuple[int, int]:
    """Границы смены по диапазону окон реально выполненных заявок."""
    start = max(SHIFT_EARLIEST, first_window_start - SHIFT_LEAD_MIN)
    end = min(SHIFT_LATEST, last_window_end + SHIFT_TAIL_MIN)
    if end - start < SHIFT_MIN_LENGTH_MIN:
        end = min(SHIFT_LATEST, start + SHIFT_MIN_LENGTH_MIN)
        if end - start < SHIFT_MIN_LENGTH_MIN:
            start = max(SHIFT_EARLIEST, end - SHIFT_MIN_LENGTH_MIN)
    return start, end


