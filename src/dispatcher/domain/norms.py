"""Нормативы работ и правила восстановления полей, которых нет в данных.

Длительности взяты из таблицы нормативов заказчика. Всё остальное - навык,
требуемый транспорт, приоритет - выводится из типа заявки и собрано здесь в
одном месте: каждое допущение можно показать эксперту и поменять одной
строкой.

Источник: таблица нормативов заказчика и справочники ТЗ (п. 2.4.1).
"""
from __future__ import annotations

from dispatcher.domain.catalog import (
    PRIORITY_HIGH,
    PRIORITY_NORMAL,
    PRIORITY_URGENT,
    SKILL_CONNECT,
    SKILL_EMERGENCY,
    SKILL_LOCAL,
    VEHICLE_CAR,
)

# --- 1. Навык -----------------------------------------------------------------
# Колонка «Тип заявки BK» ложится на справочник навыков ТЗ один в один.
SKILL_BY_TYPE_BK = {
    "Локальная заявка": SKILL_LOCAL,
    "Подключение": SKILL_CONNECT,
    "Дозаказ": SKILL_CONNECT,
    "Глобальная проблема": SKILL_EMERGENCY,
}
DEFAULT_SKILL = SKILL_LOCAL

# --- 2. Длительность работ, минуты -------------------------------------------
# Таблица нормативов заказчика («Нормативы.xlsx», прислана 16.09.2026):
#
#   Работа                              дорога  работы  документы  базовый
#   Подключение клиентов, базовая          20      60       10        90
#   Авария на ТКД                          20      80        0       100
#   Дозаказ оборудования                   20      10       10        40
#   Локальная заявка, ремонт у клиента     20      30        0        50
#
# Дорога уже входит в базовый норматив, поэтому на адресе бригада проводит
# базовый норматив минус двадцать минут, а дорогу планировщик считает свою,
# по расстоянию и транспорту. Складывать их заново значит считать дорогу
# дважды и терять час на каждой бригаде.
ROAD_IN_NORM_MIN = 20

#: Базовый норматив по колонке «Тип заявки BK», минуты вместе с дорогой.
BASE_NORM_BY_TYPE_BK = {
    "Подключение": 90,
    "Глобальная проблема": 100,
    "Дозаказ": 40,
    "Локальная заявка": 50,
}
DEFAULT_BASE_NORM = 50

# --- 3. Приоритет -------------------------------------------------------------
# Порядок задан постановщиком: авария, затем подключение, затем ремонт и
# дозаказ по остаточному принципу (чат 19.09, ответ 15; повторён 21.09).
# «Срочная» = авария (влияет на многих абонентов) либо уже просроченный наряд.
URGENT_TYPES_BK = {"Глобальная проблема"}
URGENT_STATUSES_BK = {"Просрочена"}
#: Второй приоритет: новое подключение. Дозаказ сюда не входит - постановщик
#: поставил его в один ряд с ремонтом.
HIGH_TYPES_BK = {"Подключение"}

#: Ориентир организаторов (22.09): для сетевой аварии допустимо закладывать
#: время реакции 1-2 часа. Верхнюю границу и держим для аварии, поступившей днём.
REACTION_TARGET_MIN = 120

# --- 4. Требуемый тип транспорта (ограничение «Ресурс» из ТЗ) ------------------
# Ограничение ставится только там, где работа физически требует машины:
# тяжёлое оборудование, бухта кабеля, инструмент аварийной бригады.
# В остальных заявках ограничения нет (ТЗ: «указывается только при наличии»).
CAR_REQUIRED_TYPES_HD = {"Авария", "Работа с кабелем"}
CAR_REQUIRED_IF_GIGABIT = True

# --- 5. Перемещение ----------------------------------------------------------
# Скорости и способы перемещения живут в `domain/travel.py`: бригада без
# машины собирает путь из плеч (дойти до остановки, доехать, дойти), и одной
# средней скоростью это не описывается.

# Коэффициент извилистости: по прямой (haversine) -> по улично-дорожной сети.
# 1.35 - общепринятая оценка для плотной городской застройки.
DETOUR_FACTOR = 1.35


def skill_for(type_bk: str) -> str:
    return SKILL_BY_TYPE_BK.get(type_bk.strip(), DEFAULT_SKILL)


def duration_for(type_bk: str) -> int:
    """Сколько минут бригада проводит на адресе.

    Из базового норматива вычтена дорога: её планировщик считает сам, по
    расстоянию и транспорту бригады.
    """
    base = BASE_NORM_BY_TYPE_BK.get(type_bk.strip(), DEFAULT_BASE_NORM)
    return max(1, base - ROAD_IN_NORM_MIN)


def priority_for(type_bk: str, status_bk: str) -> str:
    if type_bk.strip() in URGENT_TYPES_BK:
        return PRIORITY_URGENT
    if status_bk.strip() in URGENT_STATUSES_BK:
        return PRIORITY_URGENT
    if type_bk.strip() in HIGH_TYPES_BK:
        return PRIORITY_HIGH
    return PRIORITY_NORMAL


def required_vehicle_for(type_hd: str, gigabit: bool) -> str | None:
    if type_hd.strip() in CAR_REQUIRED_TYPES_HD:
        return VEHICLE_CAR
    if gigabit and CAR_REQUIRED_IF_GIGABIT:
        return VEHICLE_CAR
    return None
